// Builds the site into dist/: per language the home page, the privacy notice and the
// imprint (src/page.mjs + src/locales); the 404 page, the sitemap, robots.txt, the
// Apache config for the host (.htaccess), and src/assets copied as they are.
// No dependencies.
//
//   node scripts/build.mjs
//   RAPPESPALTER_VERSION=1.5.1 node scripts/build.mjs   # show the app's latest version
//
// CI sets RAPPESPALTER_VERSION to the app's latest release (.github/workflows/pages.yml).
// Without it the page simply doesn't mention a version.

import { cp, mkdir, readdir, readFile, rm, writeFile } from "node:fs/promises"
import { createHash } from "node:crypto"
import { fileURLToPath } from "node:url"
import path from "node:path"
import { LOCALES, SITE_URL } from "../src/site.mjs"
import { page, notFound, privacyPage, imprintPage, langPath, esc } from "../src/page.mjs"

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const SRC = path.join(ROOT, "src")
const DIST = path.join(ROOT, "dist")

export async function loadMessages(lang) {
  return JSON.parse(await readFile(path.join(SRC, "locales", `${lang}.json`), "utf8"))
}

// French puts a (narrow) no-break space before : ; ? ! and inside « », so they never
// start a line on their own.
function typeset(lang, text) {
  if (lang !== "fr") return text
  return text
    .replace(/ ([:;?!»])/g, " $1")
    .replace(/« /g, "« ")
}

function translator(lang, messages) {
  return (key, vars = {}) => {
    const message = messages[key]
    if (message === undefined) throw new Error(`${lang}: missing text "${key}"`)
    const filled = message.replace(/\{(\w+)\}/g, (_, name) => {
      if (!(name in vars)) throw new Error(`${lang}: "${key}" needs {${name}}`)
      return esc(vars[name])
    })
    return typeset(lang, filled)
  }
}

// Sends a first-time visitor of the root (English) page to their own language. Once
// they pick one in the header (main.js remembers it), or if their browser prefers
// none of ours, they stay.
const languageRedirect = `
  <script>
    (function () {
      try { if (localStorage.getItem("lang")) return } catch (e) { return }
      var ours = ${JSON.stringify(LOCALES.map(l => l.lang))}
      var langs = navigator.languages || [navigator.language || ""]
      for (var i = 0; i < langs.length; i++) {
        var l = String(langs[i]).slice(0, 2).toLowerCase()
        if (ours.indexOf(l) > -1) {
          if (l !== ours[0]) location.replace(l + "/" + location.hash)
          return
        }
      }
    })()
  </script>`

// The hashes of the pages' inline <script>s, for the Content Security Policy: they
// may run, nothing else inline may.
async function inlineScriptHashes() {
  const hashes = new Set()
  for (const file of (await readdir(DIST, { recursive: true })).filter(f => f.endsWith(".html"))) {
    const html = await readFile(path.join(DIST, file), "utf8")
    for (const [, code] of html.matchAll(/<script>([\s\S]*?)<\/script>/g)) {
      hashes.add(`'sha256-${createHash("sha256").update(code).digest("base64")}'`)
    }
  }
  return [...hashes]
}

// Apache config for the host (Hostpoint reads .htaccess): HTTPS only, the 404 page,
// security headers, and how long browsers may cache what.
function htaccess(scriptHashes) {
  const csp = [
    "default-src 'none'",
    `script-src 'self' ${scriptHashes.join(" ")}`,
    "style-src 'self'",
    "img-src 'self'",
    "media-src 'self'",
    "font-src 'self'",
    "base-uri 'none'",
    "form-action 'none'",
    "frame-ancestors 'none'",
  ].join("; ")
  return `# Generated by scripts/build.mjs; edit it there.

ErrorDocument 404 /404.html
Options -Indexes
DirectoryIndex index.html

<IfModule mod_rewrite.c>
  RewriteEngine On
  # HTTPS only (.dev requires it anyway), and www. to the bare domain.
  RewriteCond %{HTTPS} off [OR]
  RewriteCond %{HTTP_HOST} ^www\\. [NC]
  RewriteCond %{HTTP_HOST} ^(?:www\\.)?(.+)$ [NC]
  RewriteRule ^ https://%1%{REQUEST_URI} [L,R=301]
</IfModule>

<IfModule mod_headers.c>
  Header always set Strict-Transport-Security "max-age=63072000; includeSubDomains"
  Header always set Content-Security-Policy "${csp}"
  Header always set X-Content-Type-Options "nosniff"
  Header always set Referrer-Policy "strict-origin-when-cross-origin"
  Header always set Permissions-Policy "camera=(), microphone=(), geolocation=(), browsing-topics=()"
  Header always set Cross-Origin-Opener-Policy "same-origin"

  # Pages are checked on every visit; assets aren't fingerprinted, so they're cached
  # for a day (CSS, JS) or a week (images, video, fonts).
  <FilesMatch "\\.(html|xml|txt)$">
    Header set Cache-Control "no-cache"
  </FilesMatch>
  <FilesMatch "\\.(css|js)$">
    Header set Cache-Control "public, max-age=86400"
  </FilesMatch>
  <FilesMatch "\\.(webp|png|mp4|woff2)$">
    Header set Cache-Control "public, max-age=604800"
  </FilesMatch>
</IfModule>

AddType image/webp .webp
AddType font/woff2 .woff2
AddType video/mp4 .mp4
AddCharset utf-8 .html .css .js .xml .txt

<IfModule mod_deflate.c>
  AddOutputFilterByType DEFLATE text/html text/css text/javascript application/javascript application/xml text/plain image/svg+xml
</IfModule>
`
}

async function build() {
  const version = (process.env.RAPPESPALTER_VERSION ?? "").trim().replace(/^v/, "")
  if (version && !/^\d+\.\d+\.\d+$/.test(version)) {
    throw new Error(`RAPPESPALTER_VERSION should look like 1.5.1, not "${version}"`)
  }

  await rm(DIST, { recursive: true, force: true })
  await mkdir(DIST, { recursive: true })
  await cp(path.join(SRC, "assets"), path.join(DIST, "assets"), { recursive: true })

  for (const [i, { lang }] of LOCALES.entries()) {
    const t = translator(lang, await loadMessages(lang))
    const dir = path.join(DIST, langPath(lang))
    await mkdir(dir, { recursive: true })
    const html = page({ t, lang, version, root: i === 0 ? "" : "../", headScript: i === 0 ? languageRedirect : "" })
    await writeFile(path.join(dir, "index.html"), html)
    if (i === 0) {
      await writeFile(path.join(DIST, "404.html"), notFound({ t, lang, root: "/" }))
    }
    // One folder deeper than the language's home page.
    const legalRoot = i === 0 ? "../" : "../../"
    for (const [sub, render] of [["privacy/", privacyPage], ["imprint/", imprintPage]]) {
      await mkdir(path.join(dir, sub), { recursive: true })
      await writeFile(path.join(dir, sub, "index.html"), render({ t, lang, root: legalRoot }))
    }
  }

  const urls = ["", "privacy/", "imprint/"].flatMap(sub => LOCALES.map(({ lang }) => {
    const alternates = LOCALES.map(l =>
      `    <xhtml:link rel="alternate" hreflang="${l.tag}" href="${SITE_URL}/${langPath(l.lang)}${sub}"/>`).join("\n")
    return `  <url>\n    <loc>${SITE_URL}/${langPath(lang)}${sub}</loc>\n${alternates}\n  </url>`
  })).join("\n")
  await writeFile(path.join(DIST, "sitemap.xml"),
    `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml">\n${urls}\n</urlset>\n`)
  await writeFile(path.join(DIST, "robots.txt"), `User-agent: *\nAllow: /\n\nSitemap: ${SITE_URL}/sitemap.xml\n`)
  await writeFile(path.join(DIST, ".htaccess"), htaccess(await inlineScriptHashes()))

  console.log(`Built ${LOCALES.length} languages into dist/${version ? ` (app version ${version})` : ""}`)
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  await build()
}
